"""gen_faults.py - build the fault fingerprints the ESP32 uses to suggest WHICH fault it is.
A fingerprint is the average CHANGE of the 13 MFCCs from the machine's own healthy sound,
so it describes how a fault changes the sound rather than the sound of one particular machine.
  python gen_faults.py        (needs data/healthy and one folder per fault, matching session names)
Writes firmware/detector/faults.h"""
import glob, os, numpy as np, anomaly as A, features as F
fault_dirs = [d for d in sorted(os.listdir("data")) if d != "healthy" and glob.glob(f"data/{d}/*.npy")]
sess = lambda d: {os.path.basename(p).split("_")[0]: p for p in glob.glob(f"data/{d}/*.npy")}
H = {s: A.windows(np.load(p)).mean(1) for s, p in sess("healthy").items()}
sd = np.concatenate([h - h.mean(0) for h in H.values()]).std(0) + 1e-3          # healthy spread per coefficient
dirs = {}
for d in fault_dirs:
    deltas = [(A.windows(np.load(p)).mean(1) - H[s].mean(0)) / sd for s, p in sess(d).items() if s in H]
    if deltas: m = np.concatenate(deltas).mean(0); dirs[d] = m / np.linalg.norm(m)
CODE = {"imbalance": "IMB", "rubbing": "RUB"}
L = ["// faults.h - generated by gen_faults.py from the recordings. Do not edit by hand.",
     "// Each fault is a direction: how the 13 MFCCs move away from the learned healthy sound.",
     f"#define N_FAULTS {len(dirs)}",
     "const char* FAULT_CODE[] = {" + ", ".join(f'"{CODE.get(d, d[:3].upper())}"' for d in dirs) + "};",
     "const float FAULT_SD[N_MFCC] = {" + ", ".join(f"{x:.4f}f" for x in sd) + "};",
     "const float FAULT_DIR[N_FAULTS][N_MFCC] = {"] + \
    ["  {" + ", ".join(f"{x:.4f}f" for x in v) + "},   // " + d for d, v in dirs.items()] + ["};"]
open("firmware/detector/faults.h", "w").write("\n".join(L) + "\n")
print("wrote firmware/detector/faults.h with", list(dirs))
