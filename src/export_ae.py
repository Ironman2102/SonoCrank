"""export_ae.py - train the 26-input autoencoder on HEALTHY recordings and write it for the ESP32.
  python export_ae.py                      healthy data at the recorded speed + simulated other speeds (default)
  python export_ae.py --speeds 1.0         only the recorded speed
Speed augmentation: each healthy recording is also replayed faster and slower (all frequencies x k, vibration x k^2),
so the model learns what 'healthy' looks like over a range of engine speeds, not just one.
Writes firmware/detector/ae_model.h (plain float weights, no TensorFlow needed on the ESP32)."""
import argparse, glob, os
os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "3")
import numpy as np, anomaly as A

def resample(x, k):
    x = x.astype(float); m = x.mean(); n = int(len(x) / k)
    y = np.interp(np.arange(n) * k, np.arange(len(x)), x - m)
    return np.clip(m + y * k ** 2, 0, 4095).astype(np.uint16)

def forward(Ws, xn):                         # same maths as the C code in detector.ino
    h = xn
    for i, (w, b) in enumerate(Ws):
        h = h @ w + b
        if i < len(Ws) - 1: h = np.maximum(h, 0)
    return h

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--speeds", default="0.7,0.85,1.0,1.2,1.4"); ap.add_argument("--epochs", type=int, default=60)
    a = ap.parse_args(); ks = [float(k) for k in a.speeds.split(",")]
    files = sorted(glob.glob("data/healthy/*.npy"))
    W = np.concatenate([A.windows(resample(np.load(f), k) if k != 1.0 else np.load(f)) for f in files for k in ks])
    print(f"{len(files)} healthy recordings x {len(ks)} speeds -> {len(W)} windows")
    ae = A.AE().fit(W, a.epochs)
    sc = ae.score(W); thr = A.threshold(sc)
    Ws = [(l.get_weights()[0], l.get_weights()[1]) for l in ae.m.layers if l.get_weights()]
    xn = ae.norm(W[:50]); err = np.abs(forward(Ws, xn) - ae.m.predict(xn, verbose=0)).max()
    print(f"threshold {thr:.3f} (1.5 x worst healthy {sc.max():.3f}); numpy vs keras max diff {err:.1e}")
    f = lambda v: ", ".join(f"{x:.6g}f" for x in np.ravel(v))
    L = ["// ae_model.h - generated by export_ae.py. Do not edit by hand.",
         f"// 26-input autoencoder trained on healthy data, speeds x{a.speeds}. Input = mean and std over 30 frames of the 13 MFCCs.",
         "#define AE_AVAILABLE 1", f"#define AE_IN {Ws[0][0].shape[0]}", f"#define AE_H {Ws[0][0].shape[1]}", f"#define AE_Z {Ws[1][0].shape[1]}",
         f"const float AE_THR = {thr:.6g}f;",
         f"const float AE_MU[AE_IN] = {{{f(ae.mu)}}};", f"const float AE_SD[AE_IN] = {{{f(ae.sd)}}};"]
    names = [("AE_W1", "AE_IN][AE_H"), ("AE_W2", "AE_H][AE_Z"), ("AE_W3", "AE_Z][AE_H"), ("AE_W4", "AE_H][AE_IN")]
    for i, ((w, b), (n, dims)) in enumerate(zip(Ws, names)):
        L.append(f"const float {n}[{dims}] = {{" + ", ".join("{" + f(r) + "}" for r in w) + "};")
        L.append(f"const float AE_B{i + 1}[{len(b)}] = {{{f(b)}}};")
    os.makedirs("firmware/detector", exist_ok=True)
    open("firmware/detector/ae_model.h", "w").write("\n".join(L) + "\n")
    np.save("ae_check.npy", {"W": W[:20], "score": sc[:20]}, allow_pickle=True)
    print("wrote firmware/detector/ae_model.h", f"({sum(w.size + b.size for w, b in Ws)} parameters)")
