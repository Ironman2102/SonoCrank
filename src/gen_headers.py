"""Generates dsp_tables.h (Hann window, sparse mel filterbank, DCT matrix) from features.py
so firmware and Python use IDENTICAL numbers."""
import os, sys, numpy as np, features as F
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join("firmware", "monitor", "dsp_tables.h")
fb, dct, hann = F._FB, F._DCT, F._HANN
starts, lens, weights, offs = [], [], [], []
for row in fb:
    nz = np.nonzero(row)[0]
    s, e = nz[0], nz[-1] + 1
    starts.append(int(s)); lens.append(int(e - s)); offs.append(len(weights)); weights += row[s:e].tolist()
def arr(name, typ, a, per=8):
    a = list(a); body = ",".join(("%.9g" % v if typ == "float" else str(v)) for v in a)
    return "static const %s %s[%d] = {%s};\n" % (typ, name, len(a), body)
with open(OUT, "w") as f:
    f.write("// AUTO-GENERATED by gen_headers.py - do not edit\n#pragma once\n#include <stdint.h>\n")
    f.write(arr("HANN", "float", hann)); f.write(arr("MEL_START", "uint16_t", starts))
    f.write(arr("MEL_LEN", "uint16_t", lens)); f.write(arr("MEL_OFF", "uint16_t", offs))
    f.write(arr("MEL_W", "float", weights)); f.write(arr("DCT", "float", dct.flatten()))
print("wrote", OUT, "| mel weights:", len(weights))
